  function build() {
    var rows = [];

    FAMILIES.forEach(function (f) {
      var src = makeSource({
        slug: f.slug, name: f.name, starter: f.starter, purpose: f.purpose,
        tier: f.tier, deliverable: f.deliverable, chain: f.chain,
        mine: f.starter ? false : true
      });
      rows.push(src);

      var made = 1;
      var copies = [];
      var wantVersions = f.versions || 0;
      var wantCopies = f.total - 1 - wantVersions;

      for (var i = 0; i < wantCopies; i++) {
        var c = copyFork(src);
        copies.push(c); rows.push(c); made++;
      }
      /* Version forks land on the source AND on some copies — which is exactly
         how a slug ends up with two versions in the real table. */
      for (var v = 0; v < wantVersions; v++) {
        var target = (v === 0 || copies.length === 0) ? src : copies[v % copies.length];
        rows.push(versionFork(target, (target.version || 1) + 1));
        made++;
      }
    });

    SINGLETONS.forEach(function (s) {
      rows.push(makeSource({
        slug: s[1], name: s[0], purpose: s[5], tier: s[2],
        deliverable: s[3], chain: s[4], mine: rng() < 0.75
      }));
    });

    return rows;
  }

