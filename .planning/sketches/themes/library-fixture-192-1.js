  /**
   * LINEAGE, DERIVED — no wire field, no migration.
   *   version fork → another row shares this slug with a lower version
   *   copy fork    → this slug is `<parent>-[a-z0-9]{6}` and the parent exists
   * Returns null for an original.
   */
  function lineageOf(row, rows) {
    if (!row.parentSlug) return null;
    if (row.forkKind === "version") {
      var base = null;
      rows.forEach(function (o) {
        if (o.slug === row.slug && o.version < row.version) {
          if (!base || o.version > base.version) base = o;
        }
      });
      return base ? { kind: "version", of: base } : null;
    }
    var m = /^(.*)-[a-z0-9]{6}$/.exec(row.slug);
    if (!m) return null;
    var parent = null;
    rows.forEach(function (o) { if (o.slug === m[1]) parent = o; });
    return parent ? { kind: "copy", of: parent } : null;
  }

  function relTime(ms, now) {
    var d = (now || NOW) - ms;
    var mins = Math.round(d / 60000);
    if (mins < 60) return mins <= 1 ? "just now" : mins + " min ago";
    var hrs = Math.round(mins / 60);
    if (hrs < 24) return hrs + (hrs === 1 ? " hour ago" : " hours ago");
    var days = Math.round(hrs / 24);
    if (days === 1) return "yesterday";
    if (days < 7) return days + " days ago";
    var wks = Math.round(days / 7);
    if (wks < 5) return wks === 1 ? "last week" : wks + " weeks ago";
    var mos = Math.round(days / 30);
    return mos === 1 ? "last month" : mos + " months ago";
  }

