def _uuid(value) -> UUID:
    return value if isinstance(value, UUID) else UUID(str(value))


def _caller(current_user: dict) -> UUID:
    return _uuid(current_user["id"])


def _refuse(status_code: int, code: str, message: str) -> HTTPException:
    return HTTPException(status_code=status_code, detail={"code": code, "message": message})


def _not_found() -> HTTPException:
    return HTTPException(status_code=404, detail=_NOT_FOUND)


def _host(url: str) -> str:
    try:
        return webhook_urls.host_of(url)
    except ValueError:
        return ""


async def _checked_url(url: str) -> str:
    """The URL rules, then the reachability check off the event loop. Raises the worded 422."""
    try:
        webhook_urls.check_webhook_url(url)
    except webhook_urls.WebhookUrlError as exc:
        if exc.code == "not_https":
            raise _refuse(422, "address_refused", ADDRESS_REFUSED) from None
        if exc.code == "userinfo":
            raise _refuse(422, "invalid_url", USERINFO_REFUSED) from None
        if exc.code == "fragment":
            raise _refuse(422, "invalid_url", FRAGMENT_REFUSED) from None
        raise _refuse(422, "invalid_url", NOT_A_URL) from None
    try:
        await run_in_threadpool(egress.validate_destination, "webhook", url, None, allowed_host=webhook_urls.host_of(url))  # noqa: E501 — one line: the key_link grep reads it whole
    except egress.EgressRefused:
        # ONE sentence: no reason code and no resolved address ever reach the caller (D-24).
        raise _refuse(422, "address_refused", ADDRESS_REFUSED) from None
    return url


def _cipher_or_refuse():
    """The configured cipher, or the 503 ``no_cipher`` refusal (D-53: never a plaintext fallback)."""
    cipher = secret_cipher.get_cipher()
    if cipher is None:
        raise _refuse(503, "no_cipher", NO_CIPHER)
    return cipher


async def _audit(current_user: dict, org: UUID, action: str, endpoint_id, url: str, actor: str) -> None:
    """One audit row, explicit org (P-7 / T-167-23). Metadata is EXACTLY actor, endpoint id, host."""
    audit_supabase = await run_in_threadpool(get_service_role_supabase, str(org))
    await write_audit_entry(
        user_id=str(current_user["id"]),
        action_type=f"webhook.endpoint.{action}",
        metadata={"actor": actor, "endpoint_id": str(endpoint_id), "host": _host(url)},
        supabase=audit_supabase,
        org_id=str(org),
    )


async def _org_name(pool: asyncpg.Pool, org: UUID) -> str:
    """The active org's name, from the same read the API keys list uses. Display only: a failed read
    is "" and the list still answers."""
    try:
        switches = await api_keys_db.mcp_switches(pool, org)
    except Exception as exc:  # noqa: BLE001 — display-only, logged by type
        logger.warning("webhooks: could not read the org name for %s (%s)", org, type(exc).__name__)
        return ""
    return (switches or {}).get("org_name") or ""


def _read(row: dict) -> WebhookEndpointRead:
    return WebhookEndpointRead(
        id=str(row["id"]),
        url=row["url"],
        description=row.get("description"),
        event_types=[str(t) for t in (row.get("event_types") or [])],
        enabled=bool(row["enabled"]),
        disabled_reason=row.get("disabled_reason"),
        disabled_at=row.get("disabled_at"),
        last_success_at=row.get("last_success_at"),
        consecutive_failures=int(row.get("consecutive_failures") or 0),
        previous_secret_expires_at=row.get("previous_secret_expires_at"),
        created_at=row["created_at"],
    )


