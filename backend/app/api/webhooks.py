"""Phase 308 (HOOK-01, HOOK-02, HOOK-04, HOOK-05, HOOK-06) — managing webhook endpoints.

Two routers in one module (the ``api/api_keys.py`` shape); ``main.py`` mounts both, and the docs
coverage key stays ``router:webhooks``:

  * ``/webhooks`` — a member's OWN endpoints in the active org: list, add (the signing secret shown
    once), edit, turn off / on, roll the secret, delete, send a test, read the delivery log, resend.
  * ``/org/webhooks`` — an org admin lists EVERY endpoint in the org (host + masked path, never the
    query), turns one off (reason ``admin``), turns an admin-off one back on, deletes one. Behind
    ``require_org_manage``.

**Security posture.**

  * ⛔ **The secret leaves the server exactly twice** — the create answer and the roll answer
    (``WebhookEndpointCreated`` / ``WebhookSecretRolled``). It is generated by
    ``webhook_signer.new_secret`` and stored ONLY through ``secret_cipher.encrypt_secret``. With no
    cipher configured, creating (and rolling) is refused with 503 ``no_cipher`` and nothing is
    stored — there is no plaintext fallback (D-12 / D-53).
  * **Save-time refusal (D-23 / D-24 / D-46).** ``webhook_urls.check_webhook_url`` first (https, no
    userinfo — httpx would send it as Basic auth — no fragment), then
    ``egress.validate_destination`` under the closed ``webhook`` capability, pinned to the URL's own
    host. That function is a plain blocking ``def`` (DNS), so it runs through ``run_in_threadpool``
    (P-5, D-v2.5-01). Every internal address answers ONE sentence with no reason code and no IP.
    The sender re-checks both before every send (an address can change after it was saved).
  * **The owner predicate is in every db call** (``app/db/webhooks.py`` is the only wall: the pool
    is BYPASSRLS and the tables have no policy). A miss and someone else's endpoint both read 404.
    ``owner_id=None`` is used on ``org_router`` only.
  * **Audit (D-31, P-7):** one row per confirmed write, with an EXPLICIT ``org_id`` and metadata
    ``{actor, endpoint_id, host}`` — never a query, a path token or a secret. A repeat no-op (a
    second turn-off) writes no second row.
  * **Refusals are ``{code, message}``** (P-6): ``message`` is the sentence the UI shows, so the
    client never prints "status 429".
  * ⛔ **Nothing here logs a URL, a secret or a payload.** Logs carry ids and outcome words.
"""
