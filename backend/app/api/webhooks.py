@router.get("", response_model=WebhookEndpointList)
async def list_my_endpoints(
    current_user: dict = Depends(get_current_user),
    active_org: str = Depends(get_active_org_id),
    pool: asyncpg.Pool = Depends(get_pg_pool),
) -> WebhookEndpointList:
    """The caller's endpoints in the active org (D-04), newest first. Never a secret."""
    caller, org = _caller(current_user), _uuid(active_org)
    rows = await webhooks_db.list_endpoints_for_owner(pool, user_id=caller, org_id=org)
    return WebhookEndpointList(
        endpoints=[_read(r) for r in rows],
        cap=webhooks_db.MAX_ENDPOINTS_PER_MEMBER,
        org_name=await _org_name(pool, org),
    )


@router.post("", response_model=WebhookEndpointCreated, status_code=status.HTTP_201_CREATED)
async def create_endpoint(
    body: Annotated[WebhookEndpointCreate, Body()],
    current_user: dict = Depends(get_current_user),
    active_org: str = Depends(get_active_org_id),
    pool: asyncpg.Pool = Depends(get_pg_pool),
) -> WebhookEndpointCreated:
    """Add an endpoint in the active org. The response is the ONLY place the secret ever appears
    (the roll answer is the only other one, for a NEW secret)."""
    caller, org = _caller(current_user), _uuid(active_org)
    cipher = _cipher_or_refuse()           # D-53: before anything is checked or minted
    url = await _checked_url(body.url)
    secret = webhook_signer.new_secret()
    try:
        row = await webhooks_db.create_endpoint(
            pool,
            user_id=caller,
            org_id=org,
            url=url,
            description=body.description,
            event_types=list(body.event_types),
            secret_ciphertext=secret_cipher.encrypt_secret(secret, cipher),
        )
    except webhooks_db.EndpointCapReached:
        name = await _org_name(pool, org)
        cap = webhooks_db.MAX_ENDPOINTS_PER_MEMBER
        message = CAP_REACHED.format(cap=cap, org=name) if name else CAP_REACHED_UNNAMED.format(cap=cap)
        raise _refuse(409, "cap_reached", message) from None
    await _audit(current_user, org, "created", row["id"], row["url"], "owner")
    return WebhookEndpointCreated(endpoint=_read(row), secret=secret)


@router.patch("/{endpoint_id}", response_model=WebhookEndpointOne)
async def update_endpoint(
    endpoint_id: UUID,
    body: Annotated[WebhookEndpointUpdate, Body()],
    current_user: dict = Depends(get_current_user),
    active_org: str = Depends(get_active_org_id),
    pool: asyncpg.Pool = Depends(get_pg_pool),
) -> WebhookEndpointOne:
    """Change the address, the events or the description. A NEW address runs both checks again."""
    caller, org = _caller(current_user), _uuid(active_org)
    current = await webhooks_db.get_endpoint_for_owner(
        pool, endpoint_id=endpoint_id, user_id=caller, org_id=org
    )
    if current is None:
        raise _not_found()
    fields = body.model_fields_set
    url = None
    if body.url is not None and body.url != current["url"]:
        url = await _checked_url(body.url)
    changes: dict = {}
    if "description" in fields:
        changes["description"] = body.description
    row = await webhooks_db.update_endpoint(
        pool,
        endpoint_id=endpoint_id,
        user_id=caller,
        org_id=org,
        url=url,
        event_types=list(body.event_types) if body.event_types is not None else None,
        **changes,
    )
    if row is None:
        raise _not_found()
    if url is not None or changes or body.event_types is not None:
        await _audit(current_user, org, "updated", row["id"], row["url"], "owner")
    return WebhookEndpointOne(endpoint=_read(row))


async def _owner_toggle(
    endpoint_id: UUID, *, enabled: bool, current_user: dict, active_org: str, pool: asyncpg.Pool
) -> WebhookEndpointOne:
    caller, org = _caller(current_user), _uuid(active_org)
    row = await webhooks_db.set_endpoint_enabled(
        pool, endpoint_id=endpoint_id, org_id=org, owner_id=caller, enabled=enabled, reason=None
    )
    if row is webhooks_db.EndpointAdminOff:
        raise _refuse(403, "admin_off", ADMIN_OFF)
    if row is None:
        raise _not_found()
    if row.get("changed_now"):   # a repeat turn-off / turn-on writes no second row
        await _audit(current_user, org, "enabled" if enabled else "disabled", row["id"], row["url"], "owner")
    return WebhookEndpointOne(endpoint=_read(row))


