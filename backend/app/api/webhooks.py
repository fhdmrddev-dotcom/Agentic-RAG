# ── the sentences (UI-SPEC §Copywriting; the client shows ``message`` as written) ─────────────
ADDRESS_REFUSED = "That address can't be reached from the internet, so Syrel won't send to it."
USERINFO_REFUSED = (
    "Take out the name and password before the @. If your receiver needs a token, put it in the "
    "query instead."
)
FRAGMENT_REFUSED = "Take out the part after #."
NOT_A_URL = "That isn't a web address."
NO_CIPHER = (
    "This Syrel deployment can't store a signing secret yet, so it can't add webhooks. Ask the "
    "person who runs it to set up secret encryption."
)
CAP_REACHED = "You have {cap} endpoints in {org}, the most allowed. Delete one to add another."
CAP_REACHED_UNNAMED = (
    "You have {cap} endpoints in this organization, the most allowed. Delete one to add another."
)
ADMIN_OFF = "Only an org admin can turn this back on."
TEST_OFF = "Turn the endpoint on to send a test."
RESEND_OFF = "Resend works when the endpoint is on."
NOT_ADMIN_OFF = "Only an endpoint an org admin turned off can be turned back on here."
BAD_CURSOR = "That page of the log can't be found. Refresh the log and try again."

_NOT_FOUND = "Webhook endpoint not found."
_DELIVERY_NOT_FOUND = "Delivery not found."

LOG_PAGE_DEFAULT = 20
