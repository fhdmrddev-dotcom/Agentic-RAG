@pytest.mark.asyncio
async def test_approve_writes_desc_and_version():
    """D-04/D-07 (V3): approve writes the LIVE description, the trigger captures EXACTLY ONE new
    immutable version, ``new_skill_version_id`` links to MAX(version_number), status -> promoted."""
    from app.main import app

    pid = str(uuid4())
    store, ids = _seed(proposal_status="proposed", proposal_id=pid)
    sb = _TriggerSupabase(store)  # mirrors the 079/132 capture_skill_version trigger
    versions_before = len(store["skill_versions"])

    _override(app, user=OWNER, supabase=sb)
    try:
        async with httpx.AsyncClient(
            transport=ASGITransport(app=app), base_url="http://test"
        ) as c:
            resp = await c.post(
                f"/skills/{ids.skill_id}/description-proposals/{pid}/approve",
                headers=_H,
            )
    finally:
        _clear_overrides(app)

    assert resp.status_code == 200, f"approve {resp.status_code}: {resp.text}"
    body = resp.json()
    assert body["status"] == "promoted"
    # The live skill description was written to the proposed (winning) description.
    assert store["skills"][0]["description"] == _BETTER_DESC
    # EXACTLY ONE new immutable version captured by the trigger (no double-capture — Pitfall 2).
    assert len(store["skill_versions"]) == versions_before + 1
    new_ver = max(store["skill_versions"], key=lambda v: v["version_number"])
    assert body["new_skill_version_id"] == new_ver["id"], "must link MAX(version_number) read-back"
    # The proposal row promoted + linked, owner-scoped.
    prop = next(p for p in store["skill_proposals"] if p["id"] == pid)
    assert prop["status"] == "promoted"
    assert str(prop["new_skill_version_id"]) == new_ver["id"]


@pytest.mark.asyncio
async def test_reject_is_pure_audit():
    """D-05 (V4): reject flips to 'rejected' with new_skill_version_id NULL, no description/version
    mutation; and is KIND-GATED — an instruction proposal sent to the description-reject route 404s
    and is NOT flipped."""
    from app.main import app

    # (a) description reject is a pure audit flip.
    pid = str(uuid4())
    store, ids = _seed(proposal_status="proposed", proposal_id=pid)
    sb = _TriggerSupabase(store)  # if reject wrongly wrote skills, the trigger would add a version
    versions_before = len(store["skill_versions"])
    skills_before = [dict(s) for s in store["skills"]]

    _override(app, user=OWNER, supabase=sb)
    try:
        async with httpx.AsyncClient(
            transport=ASGITransport(app=app), base_url="http://test"
        ) as c:
            resp = await c.post(
                f"/skills/{ids.skill_id}/description-proposals/{pid}/reject",
                headers=_H,
            )
    finally:
        _clear_overrides(app)

    assert resp.status_code == 200, f"reject {resp.status_code}: {resp.text}"
    body = resp.json()
    assert body["status"] == "rejected"
    assert body["new_skill_version_id"] is None
    prop = next(p for p in store["skill_proposals"] if p["id"] == pid)
    assert prop["status"] == "rejected"
    assert prop.get("new_skill_version_id") is None
    assert len(store["skill_versions"]) == versions_before, "reject must NOT add a version"
    assert [dict(s) for s in store["skills"]] == skills_before, "reject must NOT write skills"

    # (b) KIND GUARD: an instruction proposal sent to the description-reject route 404s + is NOT flipped.
    ipid = str(uuid4())
    store2, ids2 = _seed(proposal_status="proposed", proposal_id=ipid, proposal_kind="instruction")
    sb2 = _FilterSupabase(store2)

    _override(app, user=OWNER, supabase=sb2)
    try:
        async with httpx.AsyncClient(
            transport=ASGITransport(app=app), base_url="http://test"
        ) as c:
            resp2 = await c.post(
                f"/skills/{ids2.skill_id}/description-proposals/{ipid}/reject",
                headers=_H,
            )
    finally:
        _clear_overrides(app)

    assert resp2.status_code == 404, f"wrong-kind reject must 404, got {resp2.status_code}"
    iprop = next(p for p in store2["skill_proposals"] if p["id"] == ipid)
    assert iprop["status"] == "proposed", "the instruction proposal must NOT be flipped"


@pytest.mark.asyncio
async def test_cross_user_404():
    """T-139-04/05 (V5 IDOR): OTHER_USER propose / approve / reject against OWNER's skill + proposal
    each return 404 (never 403); a malformed skill_id also 404s; NO IDOR write lands."""
    from app.main import app

    pid = str(uuid4())
    store, ids = _seed(proposal_status="proposed", proposal_id=pid)
    sb = _TriggerSupabase(store)

    _override(app, user=OTHER_USER, supabase=sb)
    try:
        async with httpx.AsyncClient(
            transport=ASGITransport(app=app), base_url="http://test"
        ) as c:
            propose_resp = await c.post(
                f"/skills/{ids.skill_id}/description-proposals",
                json={"run_id": ids.run_id},
                headers=_H,
            )
            approve_resp = await c.post(
                f"/skills/{ids.skill_id}/description-proposals/{pid}/approve",
                headers=_H,
            )
            reject_resp = await c.post(
                f"/skills/{ids.skill_id}/description-proposals/{pid}/reject",
                headers=_H,
            )
            malformed_resp = await c.post(
                "/skills/not-a-uuid/description-proposals",
                json={"run_id": ids.run_id},
                headers=_H,
            )
    finally:
        _clear_overrides(app)

    assert propose_resp.status_code == 404, f"cross-user propose {propose_resp.status_code}"
    assert approve_resp.status_code == 404, f"cross-user approve {approve_resp.status_code}"
    assert reject_resp.status_code == 404, f"cross-user reject {reject_resp.status_code}"
    assert malformed_resp.status_code == 404, f"malformed skill_id {malformed_resp.status_code}"

    # No IDOR write landed: propose inserted nothing, approve/reject did NOT touch the OWNER row/skill.
    proposals = store.get("skill_proposals", [])
    assert len(proposals) == 1, "cross-user propose must NOT insert a row"
    assert proposals[0]["status"] == "proposed", "cross-user approve/reject must NOT flip status"
    assert proposals[0]["user_id"] == OWNER["id"]
    assert store["skills"][0]["description"] == _BASE_DESC, "cross-user approve must NOT write skills"
